#!/usr/bin/env node
/**
 * Syncs the generated OpenUI library spec from the web app into the agent
 * bundle. The agent compiles agent/ in isolation — every file under agent/lib/
 * must be an authored module (eve discovery rejects .json there), so the spec
 * travels as a generated TypeScript module: agent/lib/openui-spec.ts.
 *
 * Regenerate + sync after changing the component catalog:
 *   pnpm --filter web exec openui generate src/lib/openui/library.tsx --spec \
 *     --out src/lib/openui/openui.spec.json
 *   node apps/agent/scripts/sync-openui-spec.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../web/src/lib/openui/openui.spec.json");
const dest = resolve(here, "../agent/lib/openui-spec.ts");

const spec = JSON.parse(readFileSync(src, "utf8"));

const moduleSource = `// GENERATED by apps/agent/scripts/sync-openui-spec.mjs — do not edit.
// Synced from apps/web/src/lib/openui/openui.spec.json; the catalog source of
// truth is apps/web/src/lib/openui/library.tsx.
import type { LibrarySpec } from "@openuidev/lang-core";

const spec = ${JSON.stringify(spec, null, 2)} as unknown as LibrarySpec;

export default spec;
`;

mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, moduleSource);
console.log(`Synced ${src}\n     -> ${dest}`);
